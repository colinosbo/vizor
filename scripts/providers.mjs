import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const folder = "src/lib/providers";
const entries = readdirSync(folder)
  .sort()
  .flatMap((file) => {
    if (
      !file.endsWith(".ts") ||
      ["index.ts", "registry.ts", "types.ts"].includes(file)
    )
      return [];
    const name = readFileSync(`${folder}/${file}`, "utf8").match(
      /export const (\w+): Provider\s*=/,
    )?.[1];
    return name ? [{ file: file.slice(0, -3), name }] : [];
  });
const source = `// Generated by scripts/providers.mjs. Add one adapter exporting a named Provider.\n${entries.map((e) => `import { ${e.name} } from "./${e.file}";`).join("\n")}\nexport const providerAdapters = [${entries.map((e) => e.name).join(", ")}];\n`;
if (readFileSync(`${folder}/registry.ts`, "utf8") !== source)
  writeFileSync(`${folder}/registry.ts`, source);
